// `pnpm --filter @fin/audit gen` (spec 08 §3.2): builds src/events/_index.gen.ts (AUDIT_EVENTS, the
// area of each event and the name union) from every fragment in src/events/. It loads each fragment,
// so `defineEvents`'s checks run, and refuses a name defined twice or a fragment whose area is not its
// file name. The output is git-ignored and never edited by hand (EX-07).
import { readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { type EventSpec, mergeFragments } from "./define.ts";

export const EVENTS_DIR = join(import.meta.dirname, "events");
export const INDEX_FILE = join(EVENTS_DIR, "_index.gen.ts");

export function fragmentFiles(dir: string = EVENTS_DIR): string[] {
  return readdirSync(dir)
    .filter((name) => /^[a-z][a-z0-9-]*\.ts$/.test(name) && !name.endsWith(".test.ts"))
    .sort();
}

function identifier(area: string): string {
  return area.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

export async function loadFragments(
  dir: string = EVENTS_DIR,
): Promise<{ file: string; events: Record<string, EventSpec> }[]> {
  const out: { file: string; events: Record<string, EventSpec> }[] = [];
  for (const file of fragmentFiles(dir)) {
    const module = (await import(pathToFileURL(join(dir, file)).href)) as { events?: unknown };
    if (typeof module.events !== "object" || module.events === null) {
      throw new Error(`${file}: exports no \`events\` from defineEvents`);
    }
    out.push({ file, events: module.events as Record<string, EventSpec> });
  }
  return out;
}

export function render(
  fragments: readonly { file: string; events: Record<string, EventSpec> }[],
): string {
  const { areas } = mergeFragments(fragments);
  const names = fragments.map((f) => ({
    file: f.file,
    id: identifier(f.file.replace(/\.ts$/, "")),
  }));
  const lines = [
    "// Generated by `pnpm --filter @fin/audit gen` from src/events/*.ts (spec 08 §3.2). Do not edit:",
    "// git ignores this file, and every package script that needs it regenerates it first.",
    ...names.map(({ file, id }) => `import { events as ${id} } from "./${file}";`),
    "",
    "export const AUDIT_EVENTS = {",
    ...names.map(({ id }) => `  ...${id},`),
    "} as const;",
    "",
    "export type AuditEvents = typeof AUDIT_EVENTS;",
    "export type AuditEventName = keyof AuditEvents & string;",
    "",
    "export const AUDIT_EVENT_AREAS: Readonly<Record<AuditEventName, string>> = {",
    ...Object.entries(areas)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, area]) => `  "${name}": "${area}",`),
    "};",
    "",
  ];
  return lines.join("\n");
}

export async function generate(
  dir: string = EVENTS_DIR,
  out: string = INDEX_FILE,
): Promise<boolean> {
  const text = render(await loadFragments(dir));
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    current = "";
  }
  if (current === text) return false;
  // Written beside and renamed into place: several package scripts run the generator at once under
  // turbo, and a reader must never see a half-written index.
  const temporary = `${out}.${process.pid}.tmp`;
  writeFileSync(temporary, text);
  renameSync(temporary, out);
  return true;
}

if (import.meta.main) {
  generate().catch((error: unknown) => {
    process.stderr.write(`audit gen: ${error instanceof Error ? error.message : "failed"}\n`);
    process.exitCode = 1;
  });
}
